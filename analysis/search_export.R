# =============================================================================
# search_export.R  -  AquaSilva connectivity-anchored SLR
# -----------------------------------------------------------------------------
# Search documentation for Supplementary Material S2.
#
# Inputs
#   search/search_strings.csv                        the 54 searches with their
#                                                     full Boolean strings
#   aquasilva.csv                                    Zotero export (tags)
#
# Counts are taken from the screened library, which is the record set the
# PRISMA flow diagram is built on. Each record carries one 001 tag per database
# that returned it and one 090 tag per search string that returned it. Because
# the tags sit on the record and not on the (string x database) pair, a record
# returned by H01 in Scopus and by H04 in Google Scholar also carries the pair
# H01 x Google Scholar. Pair counts are therefore NOT reported. The exact
# quantities are (a) unique records per string, (b) unique records per
# database, and (c) for each string, how many of its records came from the
# primary databases only, from Google Scholar only, or from both.
#
# Outputs
#   writeup/search_queries.tex       per-string table (exact library counts)
#   writeup/search_strings_full.tex  longtable of all 54 Boolean strings
#   writeup/search_queries.csv
#   figures/fig_S1_search.{pdf,png}  Fig. S1
# =============================================================================

suppressMessages({ library(tidyverse); library(here) })

log_csv     <- here("search", "search_strings.csv")
raw_csv     <- here("aquasilva.csv")
writeup_dir <- here("writeup");  dir.create(writeup_dir, showWarnings = FALSE)
figures_dir <- if (exists("figures_dir")) figures_dir else here("figures")
dir.create(figures_dir, showWarnings = FALSE)

okabe_ito <- c("#E69F00","#56B4E9","#009E73","#F0E442",
               "#0072B2","#D55E00","#CC79A7","#999999")

# --- search log -----------------------------------------------------------------
slog <- read_csv(log_csv, col_types = cols(.default = col_character()), na = character()) |>
  transmute(search_id, database = recode(database, GoogleScholar = "Google Scholar"),
            combination, string = search_string)
stopifnot(nrow(slog) == 54, n_distinct(slog$search_id) == 18)

# --- library tags -----------------------------------------------------------------
aq <- read_csv(raw_csv, col_types = cols(.default = col_character()), na = character()) |>
  rename_with(~ str_remove(.x, "^\uFEFF"))
tags <- aq |> select(Key, mt = `Manual Tags`) |>
  separate_rows(mt, sep = ";\\s*") |> mutate(tag = str_trim(mt)) |> filter(tag != "")

screened <- tags |> filter(str_starts(tag, "006-")) |> distinct(Key)
final    <- tags |> filter(tag == "006-Include-Final") |> distinct(Key)

q  <- tags |> filter(str_detect(tag, "^090-[HM]\\d{2}$")) |>
  transmute(Key, search_id = str_remove(tag, "^090-")) |> distinct() |>
  semi_join(screened, by = "Key")
db <- tags |> filter(str_starts(tag, "001-")) |>
  transmute(Key, db = str_remove(tag, "^001-")) |> distinct() |>
  semi_join(screened, by = "Key")

origin <- db |> group_by(Key) |>
  summarise(gs = any(db == "GoogleScholar"), prim = any(db %in% c("Scopus", "WoS")),
            .groups = "drop") |>
  mutate(origin = case_when(prim & gs ~ "Primary database and Google Scholar",
                            prim      ~ "Primary database only",
                            TRUE      ~ "Google Scholar only"))

per_db <- db |> count(db)
n_db_unique <- n_distinct(db$Key)
message(sprintf("Unique records per database: %s; unique across databases: %d",
                paste(per_db$db, per_db$n, sep = " = ", collapse = ", "), n_db_unique))

qmap <- slog |> distinct(search_id, combination) |>
  mutate(type = if_else(str_starts(search_id, "H"), "Baseline", "Mitigation"),
         blocks = str_replace_all(str_replace(combination, "\\(C1 OR C2 OR C3\\)", "C"),
                                  "\\s*\\+\\s*", " $\\\\times$ "))

qtab <- q |> left_join(origin, by = "Key") |>
  mutate(included = Key %in% final$Key) |>
  group_by(search_id) |>
  summarise(unique   = n(),
            prim_only = sum(origin == "Primary database only"),
            both      = sum(origin == "Primary database and Google Scholar"),
            gs_only   = sum(origin == "Google Scholar only"),
            included  = sum(included), .groups = "drop") |>
  right_join(qmap, by = "search_id") |>
  mutate(across(c(unique, prim_only, both, gs_only, included), ~ coalesce(.x, 0L))) |>
  arrange(search_id)
write_csv(qtab |> select(search_id, type, combination, unique, prim_only, both,
                         gs_only, included),
          file.path(writeup_dir, "search_queries.csv"))

qtex <- c(
  "% Auto-generated by search_export.R from the screening library tags.",
  "{\\small\\setlength{\\tabcolsep}{4.5pt}",
  "\\begin{longtable}{@{}l l l r r r r r@{}}",
  sprintf(paste0("\\caption{Records contributed by each search string. Counts are unique ",
                 "screened records carrying the tag of the string, split by the databases ",
                 "that returned them. A record can be returned by several strings, so the ",
                 "column totals exceed the %d unique records.}\\label{tab:queries}\\\\"),
          n_db_unique),
  "\\toprule",
  " & & & & \\multicolumn{3}{c}{Returned by} & \\\\ \\cmidrule(lr){5-7}",
  "ID & Type & Blocks & Records & \\shortstack{Primary\\\\only} & Both & \\shortstack{Scholar\\\\only} & Included \\\\",
  "\\midrule \\endfirsthead",
  "\\toprule ID & Type & Blocks & Records & Primary only & Both & Scholar only & Included \\\\ \\midrule \\endhead",
  sprintf("%s & %s & %s & %d & %d & %d & %d & %d \\\\",
          qtab$search_id, qtab$type, qtab$blocks, qtab$unique,
          qtab$prim_only, qtab$both, qtab$gs_only, qtab$included),
  "\\bottomrule",
  "\\end{longtable}}")
writeLines(qtex, file.path(writeup_dir, "search_queries.tex"))

# --- full strings ---------------------------------------------------------------
tex_tt <- function(x) x |>
  str_replace_all("\\\\", "\\\\textbackslash{}") |>
  str_replace_all("([&%$#_{}])", "\\\\\\1") |>
  str_replace_all("~", "\\\\textasciitilde{}") |>
  str_replace_all("\\^", "\\\\textasciicircum{}")

full <- slog |>
  mutate(db_order = match(database, c("Scopus", "Web of Science", "Google Scholar"))) |>
  arrange(search_id, db_order) |>
  mutate(first = !duplicated(search_id),
         id_cell = if_else(first, sprintf("%s\\newline{\\scriptsize %s}", search_id,
                                          str_replace_all(str_replace(combination, "\\(C1 OR C2 OR C3\\)", "C"), "\\s+", "")), ""),
         line = sprintf("%s%s & %s & {\\ttfamily\\scriptsize %s} \\\\",
                        if_else(first & search_id != "H01", "\\addlinespace\n", ""),
                        id_cell, database, tex_tt(string)))

ftex <- c(
  "% Auto-generated by search_export.R from the search log (54 searches).",
  "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{1.95cm} >{\\raggedright\\arraybackslash}p{1.7cm} >{\\raggedright\\arraybackslash}p{11.85cm}@{}}",
  "\\caption{Complete Boolean search strings as run in each database. Scopus strings search title, abstract, and keywords, Web of Science strings search the topic field, and Google Scholar strings use the \\texttt{intitle} operator.}\\label{tab:strings}\\\\",
  "\\toprule Query & Database & Search string \\\\ \\midrule \\endfirsthead",
  "\\toprule Query & Database & Search string \\\\ \\midrule \\endhead",
  "\\bottomrule \\endfoot",
  full$line,
  "\\end{longtable}")
writeLines(ftex, file.path(writeup_dir, "search_strings_full.tex"))

# --- Fig. S1 ----------------------------------------------------------------------
lev_origin <- c("Primary database only", "Primary database and Google Scholar",
                "Google Scholar only")
pal_origin <- setNames(c(okabe_ito[5], okabe_ito[3], okabe_ito[1]), lev_origin)

fig_dat <- qtab |>
  select(search_id, combination, prim_only, both, gs_only) |>
  pivot_longer(c(prim_only, both, gs_only), names_to = "k", values_to = "n") |>
  mutate(origin = factor(recode(k, prim_only = lev_origin[1], both = lev_origin[2],
                                gs_only = lev_origin[3]), levels = rev(lev_origin)),
         search_id = factor(search_id, levels = qtab$search_id))

x_lab <- setNames(paste0(qtab$search_id, "\n",
                         str_replace_all(str_remove(qtab$combination, "\\s*\\+\\s*D.*$"),
                                         "\\s*\\+\\s*", "\u00b7")),
                  qtab$search_id)
y_max <- max(qtab$unique)

p_s1 <- ggplot(fig_dat, aes(search_id, n, fill = origin)) +
  annotate("rect", xmin = 0.4, xmax = 9.5, ymin = -Inf, ymax = Inf, fill = "grey96") +
  annotate("rect", xmin = 9.5, xmax = 18.6, ymin = -Inf, ymax = Inf, fill = "grey92") +
  geom_col(width = 0.72, colour = "white", linewidth = 0.25) +
  geom_text(data = qtab |> mutate(search_id = factor(search_id, levels = qtab$search_id)),
            aes(search_id, unique, label = unique), inherit.aes = FALSE,
            vjust = -0.5, size = 2.8, fontface = "bold", colour = "grey20") +
  geom_text(data = qtab |> mutate(search_id = factor(search_id, levels = qtab$search_id)),
            aes(search_id, unique, label = sprintf("(%d)", included)), inherit.aes = FALSE,
            vjust = -2.1, size = 2.3, colour = "grey45") +
  annotate("text", x = 5, y = y_max * 1.27, label = "Baseline queries H (A \u00d7 B \u00d7 D)",
           size = 3, fontface = "bold", colour = "grey20") +
  annotate("text", x = 14, y = y_max * 1.27,
           label = "Mitigation queries M (A \u00d7 B \u00d7 C \u00d7 D)",
           size = 3, fontface = "bold", colour = "grey20") +
  scale_fill_manual(values = pal_origin, breaks = lev_origin, name = "Returned by") +
  scale_x_discrete(labels = x_lab) +
  scale_y_continuous(expand = expansion(mult = c(0.01, 0.06)),
                     limits = c(0, y_max * 1.32), breaks = scales::breaks_pretty(6)) +
  labs(x = NULL, y = "Unique screened records") +
  theme_minimal(base_size = 9) +
  theme(panel.grid.major.x = element_blank(), panel.grid.minor = element_blank(),
        panel.grid.major.y = element_line(colour = "grey90"),
        axis.text.x = element_text(size = 6, lineheight = 0.9),
        legend.position = "bottom", legend.title = element_text(size = 8),
        legend.text = element_text(size = 8),
        plot.caption = element_text(colour = "grey40", size = 7, hjust = 0, lineheight = 1.2),
        plot.caption.position = "plot")

ggsave(file.path(figures_dir, "fig_S1_search.pdf"), p_s1, width = 17.4, height = 10,
       units = "cm", device = cairo_pdf)
ggsave(file.path(figures_dir, "fig_S1_search.png"), p_s1, width = 17.4, height = 10,
       units = "cm", dpi = 300)

message(sprintf("Search export: 54 strings, %d unique screened records from databases; %s.",
                n_db_unique, paste(sprintf("%s %d", per_db$db, per_db$n), collapse = ", ")))
